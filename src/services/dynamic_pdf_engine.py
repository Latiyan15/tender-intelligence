    def convert_markdown_to_pdf(self, markdown_text: str, project_meta: Optional[Dict[str, Any]] = None) -> bytes:
        """Parses markdown into SimpleDocTemplate flowables and compiles the final PDF."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=36,
            rightMargin=36,
            topMargin=46,
            bottomMargin=46
        )

        project_meta = project_meta or {}
        story = []

        # Sanitize deliverable markdown: remove conversational chatter, trailing prompts, and tags
        from src.services.deliverable_cleaner import clean_deliverable_markdown
        cleaned = clean_deliverable_markdown(markdown_text)
        lines = cleaned.split('\n')

        # Extract title and subtitle for Cover Page
        cover_title = project_meta.get("title") or "Technical Solution & Budgetary Commercial Offer"
        cover_sub = ""
        client_name = project_meta.get("client_org") or ""

        # Check first heading in text
        for line in lines[:8]:
            s = line.strip()
            if s.startswith('# '):
                cover_title = s[2:].strip()
                break

        # Generate publication Cover Page
        cover_flowables = self._build_cover_page(cover_title, cover_sub, client_name)
        story.extend(cover_flowables)

        i = 0
        in_table = False
        table_lines = []
        blockquote_buffer = []

        def flush_blockquote():
            nonlocal blockquote_buffer
            if not blockquote_buffer:
                return
            full_quote_text = "<br/>".join([self._sanitize_inline_markdown(q) for q in blockquote_buffer])
            q_table = Table([[Paragraph(full_quote_text, self.blockquote_style)]], colWidths=[523])
            q_table.setStyle(TableStyle([
                ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
                ('BOX', (0,0), (-1,-1), 0.6, colors.HexColor('#E2E8F0')),
                ('LINELEFT', (0,0), (0,0), 3.5, colors.HexColor('#0284C7')),
                ('TOPPADDING', (0,0), (-1,-1), 6),
                ('BOTTOMPADDING', (0,0), (-1,-1), 6),
                ('LEFTPADDING', (0,0), (-1,-1), 10),
                ('RIGHTPADDING', (0,0), (-1,-1), 10),
            ]))
            story.append(q_table)
            story.append(Spacer(1, 6))
            blockquote_buffer = []

        while i < len(lines):
            line = lines[i]
            stripped = line.strip()

            # 1. Table Detection
            if stripped.startswith('|') and stripped.endswith('|'):
                flush_blockquote()
                in_table = True
                table_lines.append(stripped)
                i += 1
                continue
            elif in_table:
                table_flowable = self._parse_table(table_lines)
                if table_flowable:
                    story.append(table_flowable)
                    story.append(Spacer(1, 6))
                in_table = False
                table_lines = []

            # 2. Blockquote Grouping (> ...)
            if stripped.startswith('>'):
                quote_text = stripped.lstrip('>').strip()
                blockquote_buffer.append(quote_text)
                i += 1
                continue
            else:
                flush_blockquote()

            # 3. Blank lines
            if not stripped:
                i += 1
                continue

            # 4. Skip document-level H1 since Cover Page already rendered it
            if stripped.startswith('# '):
                # Optionally add a small section title or skip to prevent redundancy
                i += 1
                continue

            # 5. Horizontal Rules
            if re.match(r'^(\-{3,}|\*{3,}|_{3,})$', stripped):
                story.append(HRFlowable(width="100%", thickness=0.8, color=colors.HexColor('#CBD5E1'), spaceBefore=5, spaceAfter=7))
                i += 1
                continue

            # 6. Section Headings (##, ###, ####)
            if stripped.startswith('## '):
                h1_txt = self._sanitize_inline_markdown(stripped[3:])
                story.append(Paragraph(h1_txt, self.h1_style))
                i += 1
                continue
            elif stripped.startswith('### '):
                h2_txt = self._sanitize_inline_markdown(stripped[4:])
                story.append(Paragraph(h2_txt, self.h2_style))
                i += 1
                continue
            elif stripped.startswith('#### '):
                h3_txt = self._sanitize_inline_markdown(stripped[5:])
                story.append(Paragraph(h3_txt, self.h3_style))
                i += 1
                continue

            # 7. Unordered Lists (- , * , • )
            if re.match(r'^[\-\*\•]\s+', stripped):
                item_content = re.sub(r'^[\-\*\•]\s+', '', stripped)
                item_html = '&bull; ' + self._sanitize_inline_markdown(item_content)
                story.append(Paragraph(item_html, self.bullet_style))
                i += 1
                continue

            # 8. Ordered Lists (1. , 2. )
            if re.match(r'^\d+\.\s+', stripped):
                item_txt = self._sanitize_inline_markdown(stripped)
                story.append(Paragraph(item_txt, self.bullet_style))
                i += 1
                continue

            # 9. Standard Paragraphs
            para_html = self._sanitize_inline_markdown(stripped)
            story.append(Paragraph(para_html, self.body_style))
            i += 1

        # Flush any trailing tables or blockquotes
        flush_blockquote()
        if in_table and table_lines:
            table_flowable = self._parse_table(table_lines)
            if table_flowable:
                story.append(table_flowable)
                story.append(Spacer(1, 6))

        # Always append Authorized Signatory block at document end
        story.append(Spacer(1, 10))
        sign_block = Table(
            [[
                Paragraph("<b>SUBMITTED ON BEHALF OF:</b><br/><b>Nikom InfraSolutions Pvt. Ltd.</b><br/>E-48/3, Okhla Industrial Area Phase-II, New Delhi — 110020<br/>CIN: U72900DL2000PTC105284 &bull; GSTIN: 07AAACN1234F1Z1", self.body_style),
                Paragraph("<b>AUTHORIZED SIGNATORY:</b><br/><br/>____________________________________<br/><b>B.S Kiran Kumar</b> &bull; Director, Pre-Sales Engineering<br/>Email: tenders@nikom.in &bull; Web: www.nikom.in", self.body_style),
            ]],
            colWidths=[260, 263]
        )
        sign_block.setStyle(TableStyle([
            ('BOX', (0,0), (-1,-1), 1.0, colors.HexColor('#CBD5E1')),
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
            ('TOPPADDING', (0,0), (-1,-1), 5),
            ('BOTTOMPADDING', (0,0), (-1,-1), 5),
            ('LEFTPADDING', (0,0), (-1,-1), 8),
            ('RIGHTPADDING', (0,0), (-1,-1), 8),
        ]))
        story.append(KeepTogether([sign_block]))

        # Compile Document with Two-Pass Numbered Canvas
        doc.build(story, canvasmaker=DynamicNumberedCanvas)
        pdf_bytes = buffer.getvalue()
        buffer.close()
        return pdf_bytes


