"""
Universal Dynamic Markdown-to-PDF Engine
========================================
Converts arbitrary Markdown generated by Claude / LLMs directly into publication-grade,
executive PDF documents matching Nikom's C-DoT Gold Standard visual hierarchy.

Key Features:
- Geometric Minimalist Cover Page (Page 1) with Nikom corporate branding
- Two-pass running header and footer ("NIKOM | Budgetary and confidential", "Page X of Y")
  suppressed on Page 1, active on Page 2 onwards
- Executive 5-KPI Metric Blocks Row in solid Navy (#0F2942)
- Clean Client Submission Metadata Table (SUBMITTED TO, SUBMITTED BY, CONTACT, DATE, VALIDITY)
- Unified Blockquote Callouts with Cyan (#0284C7) left accent bar and soft #F8FAFC tint
- Intelligent Column Width Allocation with enforced minimums (eliminates 2-letter word breaks)
- Table Category Divider Rows (e.g. "A POWER INFRASTRUCTURE") spanned across full width
- Soft highlight (#FEF3C7 / #EFF6FF) for Subtotal and Grand Total rows
- Standard currency formatting (replaces Unicode ₹ with Rs. to prevent missing glyphs)
- Bullet and numbered lists with clean indentation
- Safe inline formatting (**bold**, *italic*, `code`) with automatic tag balancing
"""

