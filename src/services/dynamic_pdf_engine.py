class DynamicNumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that dynamically calculates total page count
    and renders professional running headers and footers on Page 2 onwards.
    Suppresses running header/footer on Page 1 for a clean cover page.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_footer(self, total_pages):
        # Suppress header and footer on Page 1 (Cover Page)
        if self._pageNumber == 1 and total_pages > 1:
            return

        self.saveState()
        self.setFont("Helvetica-Bold", 7.5)
        self.setFillColor(colors.HexColor('#0F2942'))
        
        # Header (Top of page)
        self.drawString(36, 808, "NIKOM")
        self.setFont("Helvetica", 7.5)
        self.setFillColor(colors.HexColor('#64748B'))
        self.drawString(82, 808, "|   Budgetary and confidential proposal")
        self.drawRightString(559, 808, f"{datetime.now().strftime('%d %B %Y')}")

        self.setStrokeColor(colors.HexColor('#CBD5E1'))
        self.setLineWidth(0.6)
        self.line(36, 802, 559, 802)

        # Footer (Bottom of page)
        self.line(36, 36, 559, 36)
        self.setFont("Helvetica", 7.2)
        self.setFillColor(colors.HexColor('#64748B'))
        self.drawString(36, 26, "Nikom InfraSolutions Pvt. Ltd.   •   Pre-Sales & Technical Solutions Engineering")
        self.drawRightString(559, 26, f"Page {self._pageNumber} of {total_pages}")
        self.restoreState()


