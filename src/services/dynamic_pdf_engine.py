    def _sanitize_inline_markdown(self, text: str) -> str:
        """Sanitizes inline markdown tags and KaTeX math into ReportLab XML."""
        if not text:
            return ""
        
        # 1. Standardize currency & bullets to eliminate missing glyph boxes
        text = text.replace('₹', 'Rs. ').replace('&#8377;', 'Rs. ').replace('&inr;', 'Rs. ')
        text = text.replace('■', '&bull;').replace('•', '&bull;')

        # 2. Convert KaTeX math expressions
        def _clean_math(match):
            m = match.group(1)
            m = re.sub(r'\times', '×', m)
            m = re.sub(r'\text\{([^}]+)\}', r'', m)
            m = re.sub(r'\cdot', '·', m)
            m = re.sub(r'\pm', '±', m)
            m = re.sub(r'\le|\leq', '≤', m)
            m = re.sub(r'\ge|\geq', '≥', m)
            m = re.sub(r'\approx', '≈', m)
            m = re.sub(r'\sim', '~', m)
            m = re.sub(r'\%', '%', m)
            m = re.sub(r'\_', '_', m)
            m = m.replace('\\', '')
            return m

        text = re.sub(r'\$(.*?)\$', _clean_math, text)

        # 3. Escape XML entities
        text = text.replace('&', '&amp;')
        text = text.replace('<', '&lt;')
        text = text.replace('>', '&gt;')

        # 4. Convert markdown bold, italic, and code
        text = re.sub(r'\*\*(.*?)\*\*', lambda m: f"<b>{m.group(1)}</b>", text)
        text = re.sub(r'__(.*?)__', lambda m: f"<b>{m.group(1)}</b>", text)
        text = re.sub(r'\*(.*?)\*', lambda m: f"<i>{m.group(1)}</i>", text)
        text = re.sub(r'`([^`]+)`', lambda m: f'<font face="Courier" color="#1D4ED8"><b>{m.group(1)}</b></font>', text)

        # Restore safe XML bullets
        text = text.replace('&amp;bull;', '&bull;')

        # 5. Tag balancing
        open_b = text.count('<b>')
        close_b = text.count('</b>')
        if open_b > close_b:
            text += '</b>' * (open_b - close_b)

        open_i = text.count('<i>')
        close_i = text.count('</i>')
        if open_i > close_i:
            text += '</i>' * (open_i - close_i)

        open_f = text.count('<font')
        close_f = text.count('</font>')
        if open_f > close_f:
            text += '</font>' * (open_f - close_f)

        return text

    def _determine_column_widths(self, rows_raw: List[List[str]], available_width: float = 523.0) -> List[float]:
        """Calculates column widths with strict minimum bounds to prevent word squishing."""
        col_count = max(len(r) for r in rows_raw)
        if col_count == 0:
            return [available_width]

        # Preset layouts tailored to technical engineering tables
        if col_count == 2:
            return [160.0, 363.0]
        elif col_count == 3:
            return [130.0, 275.0, 118.0]
        elif col_count == 4:
            # Check if first column is short like Sl. or Ref
            h0 = rows_raw[0][0].lower() if rows_raw else ""
            if any(k in h0 for k in ['sl', 'no', '#', 'item']):
                return [30.0, 175.0, 228.0, 90.0]
            return [110.0, 180.0, 143.0, 90.0]
        elif col_count == 5:
            return [28.0, 185.0, 160.0, 60.0, 90.0]
        elif col_count == 6:
            # Common BOQ format: Sl | Description | UoM | Qty | Unit Rate | Amount
            return [26.0, 195.0, 42.0, 45.0, 95.0, 120.0]
        elif col_count == 7:
            return [24.0, 165.0, 42.0, 40.0, 82.0, 90.0, 80.0]

        # Dynamic fallback: measure max characters with enforced min bounds
        max_lens = [0] * col_count
        for r in rows_raw:
            for i, cell in enumerate(r):
                max_lens[i] = max(max_lens[i], len(cell))
        
        tot_len = sum(max_lens) or 1
        widths = []
        for i, l in enumerate(max_lens):
            if i == 0 and l <= 4:
                w = 26.0
            else:
                w = max(45.0, (l / tot_len) * available_width)
            widths.append(w)
        
        # Scale to match available_width exactly
        scale = available_width / sum(widths)
        return [round(w * scale, 1) for w in widths]

    def _parse_table(self, table_lines: List[str]) -> Optional[Table]:
        """Converts Markdown table rows into a styled ReportLab Table matching C-DoT polish."""
        if len(table_lines) < 2:
            return None

        # Filter out markdown separator line (|:---|:---|)
        rows_raw = []
        for line in table_lines:
            stripped = line.strip()
            if re.match(r'^\|?\s*[-:\s|]+\s*\|?$', stripped):
                continue
            parts = [p.strip() for p in stripped.strip('|').split('|')]
            if parts:
                rows_raw.append(parts)

        if not rows_raw:
            return None

        col_count = max(len(r) for r in rows_raw)
        for r in rows_raw:
            while len(r) < col_count:
                r.append("")

        col_widths = self._determine_column_widths(rows_raw, available_width=523.0)

        table_data = []
        category_rows = []
        total_rows = []
        subtotal_rows = []

        for row_idx, r in enumerate(rows_raw):
            row_data = []
            is_header = (row_idx == 0)
            
            # Check if this is a Category Divider Row (e.g. "A POWER INFRASTRUCTURE")
            first_cell = r[0].strip()
            is_cat_divider = (
                not is_header and
                bool(re.match(r'^[A-Z][\.\s]+[A-Z\s]{4,}', first_cell)) and
                all(c.strip() == "" for c in r[1:])
            )
            if is_cat_divider:
                category_rows.append(row_idx)
                cat_txt = self._sanitize_inline_markdown(first_cell)
                row_data.append(Paragraph(f"<b>{cat_txt}</b>", self.tbl_category_style))
                for _ in range(1, col_count):
                    row_data.append("")
                table_data.append(row_data)
                continue

            # Check if Total or Subtotal
            r_str = " ".join(r).lower()
            is_total = any(w in r_str for w in ['total capex', 'grand total', 'total 5-year', 'total indicative', 'total incl'])
            is_subtotal = not is_total and any(w in r_str for w in ['subtotal', 'gst @', 'gst at'])
            
            if is_total:
                total_rows.append(row_idx)
            elif is_subtotal:
                subtotal_rows.append(row_idx)

            for col_idx, cell in enumerate(r):
                cell_text = self._sanitize_inline_markdown(cell)
                # Right align numbers / currency / percentages
                is_num = bool(re.search(r'^(?:Rs\.|\₹|\$)?\s*[\d\.,]+%?\s*(?:L|Cr|Nos\.?|Sets?|Units?|Job)?$', cell.strip(), re.I))
                align_right = (col_idx == col_count - 1 and col_count > 2) or (col_idx >= 3 and is_num)

                if is_header:
                    style = self.tbl_hdr_r_style if align_right else self.tbl_hdr_style
                elif is_total or is_subtotal:
                    style = self.tbl_cell_r_bold_style if align_right else self.tbl_cell_bold_style
                else:
                    style = self.tbl_cell_r_style if align_right else self.tbl_cell_style

                row_data.append(Paragraph(cell_text, style))
            table_data.append(row_data)

        table = Table(table_data, colWidths=col_widths, repeatRows=1)
        
        # Base TableStyle
        ts = [
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0F2942')),
            ('BOX', (0, 0), (-1, -1), 0.8, colors.HexColor('#CBD5E1')),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ('LEFTPADDING', (0, 0), (-1, -1), 4),
            ('RIGHTPADDING', (0, 0), (-1, -1), 4),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ]

        # Category Divider Rows: Span across full width with distinct accent
        for cat_idx in category_rows:
            ts.append(('SPAN', (0, cat_idx), (-1, cat_idx)))
            ts.append(('BACKGROUND', (0, cat_idx), (-1, cat_idx), colors.HexColor('#EFF6FF')))
            ts.append(('BOTTOMPADDING', (0, cat_idx), (-1, cat_idx), 4))
            ts.append(('TOPPADDING', (0, cat_idx), (-1, cat_idx), 4))
            ts.append(('LINEBELOW', (0, cat_idx), (-1, cat_idx), 1.0, colors.HexColor('#93C5FD')))

        # Alternating Rows
        for r_idx in range(1, len(rows_raw)):
            if r_idx in category_rows or r_idx in total_rows or r_idx in subtotal_rows:
                continue
            if r_idx % 2 == 1:
                ts.append(('BACKGROUND', (0, r_idx), (-1, r_idx), colors.HexColor('#FAFAFA')))

        # Subtotal Rows
        for sub_idx in subtotal_rows:
            ts.append(('BACKGROUND', (0, sub_idx), (-1, sub_idx), colors.HexColor('#F8FAFC')))
            ts.append(('LINEABOVE', (0, sub_idx), (-1, sub_idx), 0.8, colors.HexColor('#CBD5E1')))

        # Grand Total Rows: Soft yellow/amber or rich blue highlight
        for tot_idx in total_rows:
            ts.append(('BACKGROUND', (0, tot_idx), (-1, tot_idx), colors.HexColor('#EFF6FF')))
            ts.append(('LINEABOVE', (0, tot_idx), (-1, tot_idx), 1.5, colors.HexColor('#1D4ED8')))
            ts.append(('LINEBELOW', (0, tot_idx), (-1, tot_idx), 1.5, colors.HexColor('#1D4ED8')))

        table.setStyle(TableStyle(ts))
        return table

